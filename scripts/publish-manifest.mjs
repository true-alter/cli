#!/usr/bin/env node
/**
 * publish-manifest.mjs — desk↔CI artefact handshake for the npm publish set.
 *
 * The pre-publish review gates attest to a DESK-packed tarball, but the artefact npm serves is
 * CI-built at tag time. This script makes that attestation transferable:
 *
 *   generate <tarball>  — hash every file in the packed tarball and write
 *                         publish-gate-manifest.json at the repo root. Run on
 *                         the release-cut branch AFTER the specialist gates
 *                         pass, against the same tarball they scanned; commit
 *                         the manifest in the release-cut PR.
 *   verify   <tarball>  — recompute the per-file hashes from a tarball and
 *                         diff against the committed manifest. Run by
 *                         release.yml on the CI-packed tarball; ANY divergence
 *                         (changed, missing, or extra file) or a version
 *                         mismatch is a hard fail: "the bytes the specialists
 *                         attested are not the bytes being published."
 *
 * The manifest hashes file CONTENTS, so tar metadata (mtimes, ordering)
 * cannot cause false fails. Byte-equality of dist/ across desk and CI is
 * guaranteed by the embedded-plugins.lock.json pin (embed-plugin.mjs) plus
 * deterministic tsc output from the committed lockfile.
 *
 * The manifest file itself lives at the repo root and is NOT in package.json
 * `files`, so it never ships in the tarball (no self-reference).
 *
 * Born from the 2026-06-05 v0.8.10 divergence. The companion mechanical gates
 * already run in CI on the packed tarball; this closes the remaining
 * attestation gap.
 *
 * Usage:  node scripts/publish-manifest.mjs generate <tarball.tgz>
 *         node scripts/publish-manifest.mjs verify   <tarball.tgz>
 * Exit:   0 = ok, 1 = divergence/missing manifest (verify) or bad input, 2 = usage.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cliRoot = resolve(here, "..");
// ALTER_PUBLISH_MANIFEST_PATH exists for test isolation only — CI and the
// release runbook always use the committed repo-root manifest.
const manifestPath = process.env.ALTER_PUBLISH_MANIFEST_PATH
  ? resolve(process.env.ALTER_PUBLISH_MANIFEST_PATH)
  : resolve(cliRoot, "publish-gate-manifest.json");

function usage() {
  process.stderr.write(
    "usage: publish-manifest.mjs <generate|verify> <tarball.tgz>\n",
  );
  process.exit(2);
}

function fail(msg) {
  process.stderr.write(`publish-manifest: ${msg}\n`);
  process.exit(1);
}

function say(msg) {
  process.stdout.write(`publish-manifest: ${msg}\n`);
}

const [mode, tarball] = process.argv.slice(2);
if (!mode || !tarball || !["generate", "verify"].includes(mode)) usage();
if (!existsSync(tarball)) fail(`tarball not found: ${tarball}`);

/** Extract the tarball to a temp dir; return the package/ root. */
function extract(tgz) {
  const tmp = mkdtempSync(join(tmpdir(), "publish-manifest-"));
  execFileSync("tar", ["-xzf", resolve(tgz), "-C", tmp]);
  const pkgRoot = join(tmp, "package");
  if (!existsSync(pkgRoot)) fail(`tarball has no package/ root: ${tgz}`);
  return { tmp, pkgRoot };
}

/** Recursively hash every file under root → { "relative/posix/path": sha256 }. */
function hashTree(root) {
  const out = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else out[relative(root, p).split(sep).join("/")] = createHash("sha256")
        .update(readFileSync(p))
        .digest("hex");
    }
  };
  walk(root);
  return out;
}

function readPackedVersion(pkgRoot) {
  try {
    return JSON.parse(readFileSync(join(pkgRoot, "package.json"), "utf8")).version;
  } catch {
    fail(`cannot read package.json version from extracted tarball.`);
  }
}

const { tmp, pkgRoot } = extract(tarball);
try {
  const files = hashTree(pkgRoot);
  const version = readPackedVersion(pkgRoot);
  const count = Object.keys(files).length;

  if (mode === "generate") {
    const manifest = {
      $comment:
        "Per-file sha256 of the npm publish set the pre-publish specialist gates attested. " +
        "Generated by scripts/publish-manifest.mjs on the release-cut branch after the gates pass; " +
        "verified by release.yml against the CI-packed tarball. Divergence fails the release.",
      version,
      files,
    };
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
    say(`generated ${manifestPath} — version ${version}, ${count} files.`);
  } else {
    if (!existsSync(manifestPath)) {
      fail(
        `publish-gate-manifest.json missing at ${manifestPath}. Generate it on the ` +
          `release-cut branch (after the specialist gates) and commit it.`,
      );
    }
    let manifest;
    try {
      manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    } catch (err) {
      fail(`publish-gate-manifest.json unparseable: ${err.message}`);
    }
    const problems = [];
    if (manifest.version !== version) {
      problems.push(
        `version mismatch: manifest attests ${manifest.version}, tarball is ${version} ` +
          `(stale manifest — regenerate on the release-cut branch).`,
      );
    }
    const attested = manifest.files ?? {};
    for (const [f, hash] of Object.entries(attested)) {
      if (!(f in files)) problems.push(`missing from tarball (attested but absent): ${f}`);
      else if (files[f] !== hash)
        problems.push(`content divergence: ${f}\n    attested ${hash}\n    packed   ${files[f]}`);
    }
    for (const f of Object.keys(files)) {
      if (!(f in attested)) problems.push(`extra in tarball (never attested): ${f}`);
    }
    if (problems.length > 0) {
      fail(
        `CI-packed tarball does not match the specialist-attested manifest ` +
          `(${problems.length} problem(s)):\n  - ${problems.join("\n  - ")}\n` +
          `The bytes being published are not the bytes the gates attested. ` +
          `Re-run the specialist gates on the true artefact and regenerate the manifest.`,
      );
    }
    say(`verified — ${count} files match the attested manifest for ${version}.`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
