/** True if the file or directory exists. */
function fsExists(p: string): boolean {
  try {
    fs.statSync(p);
    return true;
  } catch {
    return false;
  }
}

/**
 * Read and parse a JSON file. Returns null if the file is absent;
 * throws on permission errors or JSON parse failures.
 */
function readJsonFile(filePath: string): Record<string, unknown> | null {
  let raw: string;
  try {
    raw = fs.readFileSync(filePath, "utf-8");
  } catch (err) {
    const e = err as NodeJS.ErrnoException;
    if (e.code === "ENOENT") return null;
    throw err;
  }
  return JSON.parse(raw) as Record<string, unknown>;
}

/**
 * Check whether the ALTER server entry (key "alter") is present
 * under a given root key in a JSON config file.
 *
 * Returns:
 *   "present"  -- rootKey exists and contains an "alter" sub-key
 *   "absent"   -- file or rootKey absent, or "alter" key missing
 *   "error"    -- file cannot be read / is not valid JSON
 */
function alterEntryStatus(
  configPath: string,
  rootKey: string,
): "present" | "absent" | "error" {
  let obj: Record<string, unknown> | null;
  try {
    obj = readJsonFile(configPath);
  } catch {
    return "error";
  }
  if (obj === null) return "absent";
  const root = obj[rootKey];
  if (root === null || typeof root !== "object" || Array.isArray(root)) {
    return "absent";
  }
  return "alter" in (root as object) ? "present" : "absent";
}

