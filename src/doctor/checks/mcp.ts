// mcp.alter-entry
// ---------------------------------------------------------------------------

const alterEntry: Check = {
  id: "mcp.alter-entry",
  category: "mcp",
  label: "~Alter server entry wired into every detected MCP client config",
  healClass: "SAFE-AUTOHEAL",
  live: true,
  async run(_ctx: DoctorCtx): Promise<CheckResult> {
    const probes = probeMcpHosts();
    const installed = probes.filter((p) => p.installed);
    if (installed.length === 0) {
      return {
        status: "WARN",
        detail: "no clients detected -- skipping entry check (see mcp.client-present)",
      };
    }

    const missing: string[] = [];
    const errors: string[] = [];

    for (const p of installed) {
      if (p.host.id === "claude-code") {
        // Claude Code entry is managed via `claude mcp add` (CLI), not a JSON
        // file. Probe: run `claude mcp list` and look for "alter".
        try {
          const result = await probeClaudeMcpList();
          if (result.error) {
            // claude binary missing -- mcp.client-present covers this;
            // treat as unknown here.
            continue;
          }
          const out = (result.stdout ?? "") + (result.stderr ?? "");
          if (!out.includes("alter")) {
            missing.push(p.host.label);
          }
        } catch {
          // Probe failed; don't double-report.
        }
        continue;
      }

      // JSON-file clients (cursor, claude-desktop, vscode).
      const h = p.host as McpHostFile;
      const status = alterEntryStatus(h.configPath, h.rootKey);
      if (status === "absent") {
        missing.push(h.label);
      } else if (status === "error") {
        errors.push(`${h.label}: ${h.configPath} could not be read or parsed`);
      }
    }

    if (errors.length > 0) {
      return {
        status: "WARN",
        detail: errors.join("; "),
        remedy: "check file permissions or hand-fix the JSON, then re-run `alter wire`",
      };
    }
    if (missing.length > 0) {
      return {
        status: "FAIL",
        detail: `Alter entry missing from: ${missing.join(", ")}`,
        remedy:
          "run `alter doctor --fix` to auto-wire, or run `alter wire` manually",
      };
    }
    return {
      status: "OK",
      detail: `Alter entry present in all ${installed.length} detected client${installed.length === 1 ? "" : "s"}`,
    };
  },

  async heal(_ctx: DoctorCtx): Promise<HealResult> {
    // Re-run probe to find only the clients missing the entry.
    const probes = probeMcpHosts();
    const installed = probes.filter((p) => p.installed);
    const missingIds: string[] = [];

    for (const p of installed) {
      if (p.host.id === "claude-code") {
        try {
          const result = await probeClaudeMcpList();
          if (!result.error) {
            const out = (result.stdout ?? "") + (result.stderr ?? "");
            if (!out.includes("alter")) missingIds.push(p.host.id);
          }
        } catch {
          // Leave claude-code out of the targeted list; wire() without --only
          // will cover it.
        }
        continue;
      }
      const h = p.host as McpHostFile;
      if (alterEntryStatus(h.configPath, h.rootKey) === "absent") {
        missingIds.push(h.id);
      }
    }

    if (missingIds.length === 0) {
      return { applied: false, status: "OK", detail: "no missing entries -- nothing to fix" };
    }

    // Delegate to the real wire surface. Pass --only for the affected clients,
    // --yes to skip the interactive prompt, so it runs non-interactively.
    try {
      await wire(["--only", missingIds.join(","), "--yes"]);
      return {
        applied: true,
        status: "OK",
        detail: `ran \`alter wire --only ${missingIds.join(",")}\``,
      };
    } catch (err) {
      return {
        applied: false,
        status: "FAIL",
        detail: `wire failed: ${(err as Error).message}`,
      };
    }
  },
};

