const sdkInstalled: Check = {
  id: "mcp.sdk-installed",
  category: "mcp",
  label: "@truealter/sdk resolvable (required by mcp-bridge)",
  healClass: "DIAGNOSE-ONLY",
  async run(_ctx: DoctorCtx): Promise<CheckResult> {
    // mcp-bridge.ts resolves @truealter/sdk via createRequire(import.meta.url).
    // Mirror that resolution here.
    const require = createRequire(import.meta.url);
    try {
      const resolved = require.resolve("@truealter/sdk");
      if (!fsExists(resolved)) {
        return {
          status: "FAIL",
          detail: `@truealter/sdk resolved to ${resolved} but file is absent`,
          remedy: "reinstall: npm install @truealter/sdk",
        };
      }
      return { status: "OK", detail: resolved };
    } catch {
      return {
        status: "FAIL",
        detail: "@truealter/sdk not resolvable from the CLI package root",
        remedy:
          "reinstall the CLI or run: npm install @truealter/sdk",
      };
    }
  },
};

