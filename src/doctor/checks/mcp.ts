// mcp.bridge-handshake (live probe)
// ---------------------------------------------------------------------------

/**
 * Locate the mcp-bridge.js file the same way mcp-bridge.ts does:
 * resolve @truealter/sdk then look for mcp-bridge.js in the dist tree.
 * Returns null if not found (i.e. sdk not installed).
 */
function findBridgePath(): string | null {
  const require = createRequire(import.meta.url);
  try {
    const sdkEntry = require.resolve("@truealter/sdk");
    const sdkDir = path.dirname(sdkEntry);
    const candidate = path.resolve(sdkDir, "mcp-bridge.js");
    if (fsExists(candidate)) return candidate;
    const binCandidate = path.resolve(sdkDir, "bin", "mcp-bridge.js");
    if (fsExists(binCandidate)) return binCandidate;
  } catch {
    // sdk not resolvable
  }
  // Sibling dist path (dev checkout).
  const here = path.dirname(fileURLToPath(import.meta.url));
  const localCandidate = path.resolve(
    here,
    "..",
    "..",
    "node_modules",
    "@truealter",
    "sdk",
    "dist",
    "mcp-bridge.js",
  );
  if (fsExists(localCandidate)) return localCandidate;
  return null;
}

const bridgeHandshake: Check = {
  id: "mcp.bridge-handshake",
  category: "mcp",
  label: "MCP bridge responds to initialize handshake",
  healClass: "DIAGNOSE-ONLY",
  live: true,
  async run(ctx: DoctorCtx): Promise<CheckResult> {
    const bridgePath = findBridgePath();
    if (!bridgePath) {
      return {
        status: "WARN",
        detail: "bridge script not found (mcp.sdk-installed may also be failing)",
        remedy: "reinstall @truealter/sdk",
      };
    }

    const timeout = Math.min(ctx.timeoutMs, 3000);

    return new Promise<CheckResult>((resolve) => {
      let settled = false;
      let stdout = "";
      let timedOut = false;

      const timer = setTimeout(() => {
        timedOut = true;
        if (!settled) {
          settled = true;
          child.kill("SIGTERM");
          resolve({
            status: "WARN",
            detail: `bridge did not respond within ${timeout}ms`,
            remedy:
              "check network connectivity to mcp.truealter.com, or run `alter mcp-bridge` to inspect output",
          });
        }
      }, timeout);

      const child = spawn(process.execPath, [bridgePath], {
        stdio: ["pipe", "pipe", "pipe"],
        env: { ...process.env },
      });

      child.on("error", (err) => {
        clearTimeout(timer);
        if (!settled) {
          settled = true;
          resolve({
            status: "WARN",
            detail: `bridge spawn error: ${err.message}`,
            remedy: "reinstall @truealter/sdk",
          });
        }
      });

      child.stdout?.on("data", (chunk: Buffer) => {
        stdout += chunk.toString("utf-8");
        // Look for a valid JSON-RPC response line.
        const lines = stdout.split("\n");
        for (const line of lines) {
          const trimmed = line.trim();
          if (!trimmed) continue;
          try {
            const msg = JSON.parse(trimmed) as Record<string, unknown>;
            if (msg.jsonrpc === "2.0" && "result" in msg) {
              clearTimeout(timer);
              if (!settled) {
                settled = true;
                child.kill("SIGTERM");
                resolve({ status: "OK", detail: "bridge returned initialize result" });
              }
              return;
            }
          } catch {
            // not a complete JSON line yet -- accumulate
          }
        }
      });

      child.on("exit", (code) => {
        clearTimeout(timer);
        if (!settled) {
          settled = true;
          if (timedOut) return; // already resolved
          resolve({
            status: "WARN",
            detail: `bridge exited (${String(code)}) before responding`,
            remedy:
              "run `alter mcp-bridge` to inspect stderr output",
          });
        }
      });

      // Send an MCP initialize request to the bridge's stdin.
      // The request is intentionally unauthenticated -- we only probe that
      // the bridge binary starts and speaks JSON-RPC correctly.
      const initRequest = JSON.stringify({
        jsonrpc: "2.0",
        id: 1,
        method: "initialize",
        params: {
          protocolVersion: "2024-11-05",
          capabilities: {},
          clientInfo: { name: "alter-doctor", version: "0" },
        },
      }) + "\n";

      try {
        child.stdin?.write(initRequest);
        child.stdin?.end();
      } catch {
        // If stdin write fails, the exit handler will resolve.
      }
    });
  },
};

