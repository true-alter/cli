const clientPresent: Check = {
  id: "mcp.client-present",
  category: "mcp",
  label: "at least one MCP client detected (Claude Code, Cursor, Desktop, VS Code)",
  healClass: "DIAGNOSE-ONLY",
  live: true,
  async run(_ctx: DoctorCtx): Promise<CheckResult> {
    const probes = probeMcpHosts();
    const detected = probes.filter((p) => p.installed);
    if (detected.length === 0) {
      return {
        status: "WARN",
        detail: "no MCP client directories found",
        remedy:
          "install Claude Code, Cursor, Claude Desktop, or VS Code, then run `alter wire`",
      };
    }
    const labels = detected.map((p) => p.host.label).join(", ");
    return {
      status: "OK",
      detail: `${detected.length} client${detected.length === 1 ? "" : "s"}: ${labels}`,
    };
  },
};

