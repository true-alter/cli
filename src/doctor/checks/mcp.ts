const collectiveBinary: Check = {
  id: "mcp.collective-binary",
  category: "mcp",
  label: "Org Alter MCP reachable",
  healClass: "DIAGNOSE-ONLY",
  async run(_ctx: DoctorCtx): Promise<CheckResult> {
    let bin: import("../../lib/mcp-config.js").OrgAlterBin;
    try {
      // resolveOrgAlterBin walks up from import.meta.url.
      // For the check, pass the check module's own URL as start so it
      // walks from the same root the CLI itself would.
      const here = path.dirname(fileURLToPath(import.meta.url));
      bin = resolveOrgAlterBin(here);
    } catch {
      // Resolution failed. Org Alter MCP is optional and not present on
      // most machines; treat a resolver miss as "not configured", with no
      // wiring instructions, rather than a fault.
      return {
        status: "OK",
        detail: "Org Alter MCP not configured (optional)",
      };
    }

    if (bin.kind === "unavailable") {
      // Org Alter MCP is optional and not present here. Informational, not
      // a failure: a CLI install is not expected to carry it.
      return {
        status: "OK",
        detail: "Org Alter MCP not configured (optional)",
      };
    }

    // Reachable target resolved and trust-verified by resolveOrgAlterBin.
    if (!fsExists(bin.path)) {
      return {
        status: "OK",
        detail: "Org Alter MCP not configured (optional)",
      };
    }
    return { status: "OK", detail: "Org Alter MCP reachable" };
  },
};

