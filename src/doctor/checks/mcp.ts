/**
 * doctor/checks/mcp.ts -- MCP client wiring diagnostic checks.
 *
 * Five checks verifying that MCP clients are present, the ALTER server
 * entry is wired into each, the @truealter/sdk bridge dependency is
 * resolvable, an optional Org Alter MCP target is reachable, and the
 * bridge can complete an initialize handshake.
 *
 * All checks are LOCAL (no phone-home). The live probe (mcp.bridge-handshake)
 * spawns the bridge binary with a bounded timeout and writes an MCP JSON-RPC
 * initialize frame to its stdin. No session data or credentials are
 * transmitted in the probe; the request is intentionally unauthenticated.
 *
 * Policy: diagnose-first; --fix opt-in only.
 * Cryptographic keys are never regenerated by doctor.
 *
 * Reads MCP host config and the bundled bridge dependency.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { spawn, exec, execFile } from "node:child_process";

import {
  defaultMcpHosts,
  probeMcpHosts,
  resolveOrgAlterBin,
  type McpHostFile,
} from "../../lib/mcp-config.js";

/** Result shape mirroring the spawnSync contract the call sites consume:
 *  `.error` is set ONLY for spawn failure / timeout-kill - a non-zero exit
 *  still carries usable stdout/stderr. */
interface ClaudeMcpListProbe {
  error: Error | null;
  stdout: string;
  stderr: string;
}

/**
 * Probe `claude mcp list`.
 *
 * ASYNC on purpose: the prior spawnSync blocked the Node event loop for the
 * full run of `claude mcp list` (seconds), which froze the doctor progress
 * line, defeated the per-check async timeout, and buffered keypresses that
 * later double-fired "press enter to return". exec/execFile keep the loop
 * free so the doctor stays paintable and cancellable.
 *
 * On Windows the `claude` shim is a `.cmd`/`.ps1` wrapper, which Node
 * refuses to spawn directly (EINVAL, CVE-2024-27980 hardening) - a shell
 * is required, so the shell path passes ONE fixed literal command string.
 * No user input is interpolated - the command is a constant - so there is
 * no injection surface.
 */
function probeClaudeMcpList(): Promise<ClaudeMcpListProbe> {
  return new Promise((resolve) => {
    const onDone = (
      error: (Error & { code?: unknown; killed?: boolean }) | null,
      stdout: string,
      stderr: string,
    ): void => {
      // Mirror spawnSync semantics: `.error` only for spawn failure
      // (binary missing) or the timeout kill - a non-zero exit with
      // output is still inspectable.
      const spawnFailure =
        error && (error.code === "ENOENT" || error.killed === true)
          ? error
          : null;
      resolve({ error: spawnFailure, stdout: stdout ?? "", stderr: stderr ?? "" });
    };
    if (process.platform === "win32") {
      exec("claude mcp list", { encoding: "utf8", timeout: 5000 }, onDone);
    } else {
      execFile("claude", ["mcp", "list"], { encoding: "utf8", timeout: 5000 }, onDone);
    }
  });
}
